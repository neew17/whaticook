// One-time enrichment script: fetches background photos for the Doces/Salgados split
// screen from Pexels and writes the result to src/data/tipoPratoImages.ts.
//
// Usage: PEXELS_API_KEY=xxx node scripts/fetch-tipo-prato-images.mjs

import { writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const API_KEY = process.env.PEXELS_API_KEY;
if (!API_KEY) {
  console.error('Missing PEXELS_API_KEY environment variable.');
  process.exit(1);
}

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUTPUT_PATH = path.join(__dirname, '..', 'src', 'data', 'tipoPratoImages.ts');

const QUERIES = {
  doce: 'brazilian desserts sweets flat lay',
  salgado: 'brazilian savory food spread flat lay',
};

async function fetchImage(query) {
  const params = new URLSearchParams({ query, per_page: '1', orientation: 'portrait' });
  const res = await fetch(`https://api.pexels.com/v1/search?${params.toString()}`, {
    headers: { Authorization: API_KEY },
  });
  if (!res.ok) throw new Error(`Pexels error ${res.status} for query "${query}"`);
  const data = await res.json();
  const photo = data.photos && data.photos[0];
  if (!photo) return null;
  return {
    url: photo.src.large2x,
    photographer: photo.photographer,
    photographerUrl: photo.photographer_url,
  };
}

async function main() {
  const results = {};
  for (const [key, query] of Object.entries(QUERIES)) {
    const image = await fetchImage(query);
    if (image) {
      results[key] = image;
      console.log(`OK   ${key} -> "${query}"`);
    } else {
      console.log(`MISS ${key} -> "${query}" (no results)`);
    }
  }

  const fileContent = `// Auto-generated by scripts/fetch-tipo-prato-images.mjs — do not hand-edit.
// Photos courtesy of Pexels (https://www.pexels.com), free to use under the Pexels License.

export interface TipoPratoImage {
  url: string;
  photographer: string;
  photographerUrl: string;
}

export const TIPO_PRATO_IMAGES: Record<'doce' | 'salgado', TipoPratoImage> = ${JSON.stringify(results, null, 2)};
`;

  writeFileSync(OUTPUT_PATH, fileContent, 'utf-8');
  console.log(`\nDone. Saved to ${OUTPUT_PATH}`);
}

main();
